/*
 * IMPORTANT:
 *
 * The main Canvas stays pointer-events-none so it doesn't
 * interfere with your website.
 *
 * This small DOM area sits exactly over the bouquet and owns
 * the mouse interaction.
 */
export const BouquetInteraction = ({ rotationRef }) => {
  const draggingRef = useRef(false);

  const pointerRef = useRef({
    x: 0,
    y: 0,
  });

  const onPointerDown = useCallback(
    (event) => {
      event.preventDefault();

      draggingRef.current = true;

      pointerRef.current.x =
        event.clientX;

      pointerRef.current.y =
        event.clientY;

      event.currentTarget.setPointerCapture(
        event.pointerId
      );
    },
    []
  );

  const onPointerMove = useCallback(
    (event) => {
      if (!draggingRef.current) {
        return;
      }

      const dx =
        event.clientX -
        pointerRef.current.x;

      const dy =
        event.clientY -
        pointerRef.current.y;

      pointerRef.current.x =
        event.clientX;

      pointerRef.current.y =
        event.clientY;

      /*
       * SHIFT = roll around Z.
       *
       * Normal drag:
       *   horizontal → Y rotation
       *   vertical   → X rotation
       *
       * Shift drag:
       *   horizontal → Z rotation
       */
      if (event.shiftKey) {
        rotationRef.current.z +=
          dx * 0.012;

        rotationRef.current.y +=
          dy * 0.004;
      } else {
        rotationRef.current.y +=
          dx * 0.012;

        rotationRef.current.x +=
          dy * 0.012;
      }

      /*
       * Keep values numerically sane.
       * There is no visual restriction here because rotation
       * naturally wraps around.
       */
      const max =
        Math.PI * 100;

      rotationRef.current.x =
        THREE.MathUtils.clamp(
          rotationRef.current.x,
          -max,
          max
        );

      rotationRef.current.y =
        THREE.MathUtils.clamp(
          rotationRef.current.y,
          -max,
          max
        );

      rotationRef.current.z =
        THREE.MathUtils.clamp(
          rotationRef.current.z,
          -max,
          max
        );
    },
    [rotationRef]
  );

  const releasePointer = useCallback(
    (event) => {
      draggingRef.current = false;

      if (
        event.currentTarget.hasPointerCapture?.(
          event.pointerId
        )
      ) {
        event.currentTarget.releasePointerCapture(
          event.pointerId
        );
      }
    },
    []
  );

  return (
    <div
      className="pointer-events-auto absolute z-[60] cursor-grab active:cursor-grabbing"

      /*
       * ========================================================
       * INTERACTION AREA POSITION
       * ========================================================
       *
       * This is the SCREEN position of the bouquet interaction
       * area.
       *
       * Adjust these values later if needed.
       */
      style={{
        width: "420px",
        height: "520px",
        right: "6vw",
        top: "17vh",

        /*
         * Don't let this area accidentally block the rest
         * of the site.
         */
        touchAction: "none",
      }}

      onPointerDown={onPointerDown}
      onPointerMove={onPointerMove}
      onPointerUp={releasePointer}
      onPointerCancel={releasePointer}

      aria-label="Interactive flower bouquet"
      role="img"
    >
      {/* Invisible interaction surface */}
    </div>
  );
};


