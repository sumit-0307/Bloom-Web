const Butterflies = ({
  visibleRef,
}) => {
  const gltf =
    useLoader(
      GLTFLoader,
      BUTTERFLY_URL
    );

  const groupRef =
    useRef();

  const norm =
    useMemo(() => {
      const box =
        new THREE.Box3()
          .setFromObject(
            gltf.scene
          );

      const size =
        box.getSize(
          new THREE.Vector3()
        );

      const center =
        box.getCenter(
          new THREE.Vector3()
        );

      const s =
        0.85 /
        Math.max(
          size.x,
          size.y,
          size.z
        );

      return {
        s,
        offX:
          -center.x,
        offY:
          -center.y,
        offZ:
          -center.z,
      };
    }, [gltf]);

  useFrame(
    (_, delta) => {
      if (
        !groupRef.current
      ) {
        return;
      }

      const target =
        visibleRef.current;

      const cur =
        groupRef.current
          .userData
          .op ?? 0;

      const next =
        damp(
          cur,
          target,
          5,
          delta
        );

      groupRef.current
        .userData
        .op = next;

      groupRef.current.visible =
        next > 0.01;

      groupRef.current.traverse(
        (o) => {
          if (
            o.isMesh &&
            o.material
          ) {
            o.material.transparent =
              true;

            o.material.opacity =
              Math.min(
                1,
                next
              );
          }
        }
      );

      groupRef.current.position.y =
        (1 - next) *
        -1.5;
    }
  );

  return (
    <group
      ref={groupRef}
      visible={false}
    >
      {[
        1,
        2,
        3,
        4,
        5,
        6,
        7,
      ].map((s) => (
        <Butterfly
          key={s}
          gltf={gltf}
          norm={norm}
          seed={s}
        />
      ))}
    </group>
  );
};


