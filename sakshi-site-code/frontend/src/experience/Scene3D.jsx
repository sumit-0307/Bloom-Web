const Butterfly = ({
  gltf,
  norm,
  seed = 0,
}) => {
  const pathRef = useRef();

  const clone = useMemo(() => {
    const c =
      SkeletonUtils.clone(
        gltf.scene
      );

    c.traverse((o) => {
      if (
        o.isMesh ||
        o.isSkinnedMesh
      ) {
        o.frustumCulled = false;
        o.material.transparent = true;
      }
    });

    return c;
  }, [gltf]);

  const mixer = useMemo(
    () =>
      new THREE.AnimationMixer(
        clone
      ),
    [clone]
  );

  const rand = useMemo(
    () => ({
      r:
        1.6 +
        (seed % 5) *
          0.35,

      hs:
        0.4 +
        ((seed * 0.13) %
          0.4),

      off:
        seed * 0.9,

      yOff:
        (seed % 3) *
          0.6 -
        0.4,

      scale:
        0.8 +
        (seed % 3) *
          0.14,
    }),
    [seed]
  );

  useEffect(() => {
    const clip =
      gltf.animations.find(
        (a) =>
          a.name ===
          "Flying"
      ) ||
      gltf.animations[0];

    if (!clip) {
      return;
    }

    const action =
      mixer.clipAction(
        clip
      );

    action.timeScale =
      0.85 +
      (seed % 4) *
        0.18;

    action.time =
      (seed * 0.37) %
      clip.duration;

    action.play();

    return () =>
      mixer.stopAllAction();
  }, [
    mixer,
    gltf,
    seed,
  ]);

  useFrame(
    (state, delta) => {
      mixer.update(delta);

      const t =
        state.clock.elapsedTime +
        rand.off;

      if (
        pathRef.current
      ) {
        pathRef.current.position.set(
          Math.cos(
            t * rand.hs
          ) *
            rand.r,

          Math.sin(
            t *
              rand.hs *
              1.3
          ) *
            0.6 +
            rand.yOff,

          Math.sin(
            t *
              rand.hs *
              0.7
          ) *
            0.8
        );

        const vx =
          -Math.sin(
            t * rand.hs
          ) *
          rand.hs *
          rand.r;

        const vz =
          Math.cos(
            t *
              rand.hs *
              0.7
          ) *
          0.7 *
          rand.hs *
          0.8;

        pathRef.current.rotation.y =
          Math.atan2(
            vx,
            vz
          );

        pathRef.current.rotation.z =
          Math.sin(
            t * rand.hs
          ) *
          0.25;

        pathRef.current.rotation.x =
          Math.sin(
            t *
              rand.hs *
              1.3
          ) *
          0.12;
      }
    }
  );

  return (
    <group ref={pathRef}>
      <group
        scale={
          norm.s *
          rand.scale
        }
      >
        <primitive
          object={clone}
          position={[
            norm.offX,
            norm.offY,
            norm.offZ,
          ]}
        />
      </group>
    </group>
  );
};


