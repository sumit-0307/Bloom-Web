/* ============================================================
   HELPERS
   ============================================================ */

const smoothstep = (edge0, edge1, x) => {
  const t = Math.min(
    1,
    Math.max(0, (x - edge0) / (edge1 - edge0))
  );

  return t * t * (3 - 2 * t);
};


/*
 * Frame-rate independent smoothing.
 */
const damp = (cur, target, k, delta) => {
  return (
    cur +
    (target - cur) *
      (1 - Math.exp(-k * delta))
  );
};


/* ============================================================
   HERO BOUQUET
   ============================================================ */

export const HeroBouquet = ({ rotationRef, visibleRef }) => {
  const gltf = useLoader(GLTFLoader, BOUQUET_URL);

  const groupRef = useRef(null);

  /*
   * Clone the model so it is safe to manipulate independently.
   */
  const clone = useMemo(() => {
    const cloned = SkeletonUtils.clone(gltf.scene);

    cloned.traverse((object) => {
      if (object.isMesh || object.isSkinnedMesh) {
        object.frustumCulled = true;

        /*
         * Clone materials as well.
         * This prevents future visual changes to the bouquet
         * from accidentally modifying another instance.
         */
        if (object.material) {
          object.material = object.material.clone();
        }
      }
    });

    return cloned;
  }, [gltf]);

  /*
   * Automatically normalize the model.
   *
   * This means your Blender export can be large or tiny and we
   * still bring it into a predictable size for the scene.
   */
  const norm = useMemo(() => {
    const box = new THREE.Box3().setFromObject(clone);

    const size = box.getSize(
      new THREE.Vector3()
    );

    const center = box.getCenter(
      new THREE.Vector3()
    );

    const maxDimension = Math.max(
      size.x,
      size.y,
      size.z
    );

    const scale =
      maxDimension > 0
        ? 2.90 / maxDimension
        : 1;

    return {
      scale,
      offsetX: -center.x,
      offsetY: -center.y,
      offsetZ: -center.z,
    };
  }, [clone]);

  /*
   * Reset the model's starting rotation whenever the model loads.
   */
  useEffect(() => {
    rotationRef.current.x = 0;
    rotationRef.current.y = 0;
    rotationRef.current.z = 0;
  }, [rotationRef]);

  /*
   * Frame loop.
   *
   * The bouquet itself has NO automatic rotation.
   * It only follows the rotation values coming from the
   * DOM interaction layer.
   */
  useFrame((_, delta) => {
    if (!groupRef.current) {
      return;
    }

    const targetOpacity = visibleRef.current;

    const currentOpacity =
      groupRef.current.userData.opacity ?? 0;

    const opacity = damp(
      currentOpacity,
      targetOpacity,
      7,
      delta
    );

    groupRef.current.userData.opacity =
      opacity;

    groupRef.current.visible =
      opacity > 0.01;

    /*
     * Fade all materials with the chapter.
     */
    groupRef.current.traverse((object) => {
      if (
        object.isMesh &&
        object.material
      ) {
        object.material.transparent = true;
        object.material.opacity = opacity;
      }
    });

    /*
     * Smoothly follow the rotation generated by
     * the interaction layer.
     */
    groupRef.current.rotation.x = damp(
      groupRef.current.rotation.x,
      rotationRef.current.x,
      14,
      delta
    );

    groupRef.current.rotation.y = damp(
      groupRef.current.rotation.y,
      rotationRef.current.y,
      14,
      delta
    );

    groupRef.current.rotation.z = damp(
      groupRef.current.rotation.z,
      rotationRef.current.z,
      14,
      delta
    );
  });

  return (
    <group
      ref={groupRef}
      visible={false}

      /*
       * FIXED 3D COORDINATES
       *
       * x = right side of hero
       * y = slightly above center
       * z = front/back position
       *
       * These are deliberately NOT based on scroll.
       */
      position={[1.9, 0.05, 0]}
    >
      <group
        scale={norm.scale}
      >
        <primitive
          object={clone}
          position={[
            norm.offsetX,
            norm.offsetY,
            norm.offsetZ,
          ]}
        />
      </group>
    </group>
  );
};


